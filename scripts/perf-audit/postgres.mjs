/**
 * Provides the PostgreSQL server for `--db postgres`: EMDASH_TEST_PG when set,
 * otherwise a disposable local cluster created with initdb.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

import { availablePort } from "./ports.mjs";

const ROOT = resolve(import.meta.dirname, "../..");
const CLUSTER_DIR = join(ROOT, ".perf-audit/pg/data");
const PG_LOG = join(ROOT, ".perf-audit/pg/server.log");

const fixtureRequire = createRequire(join(ROOT, "fixtures/perf-site/package.json"));

function runOrThrow(command, args) {
	const result = spawnSync(command, args, { encoding: "utf8" });
	if (result.error?.code === "ENOENT") {
		throw new Error(
			`${command} was not found. Install PostgreSQL or set EMDASH_TEST_PG to a role with CREATEDB.`,
		);
	}
	if (result.status !== 0)
		throw new Error(`${command} failed:\n${result.stdout}\n${result.stderr}`);
}

function withDatabase(url, name) {
	const parsed = new URL(url);
	parsed.pathname = `/${name}`;
	return parsed.toString();
}

/** Starts or attaches to PostgreSQL and returns a handle for creating per-run databases. */
export async function startPostgres() {
	const external = process.env.EMDASH_TEST_PG;
	let adminUrl = external;

	if (!external) {
		if (!existsSync(join(CLUSTER_DIR, "PG_VERSION"))) {
			mkdirSync(dirname(CLUSTER_DIR), { recursive: true });
			runOrThrow("initdb", [
				"-D",
				CLUSTER_DIR,
				"-U",
				"postgres",
				"--auth=trust",
				"-E",
				"UTF8",
				"--locale=C",
			]);
		}
		const port = await availablePort();
		spawnSync("pg_ctl", ["-D", CLUSTER_DIR, "-m", "immediate", "stop"], { stdio: "ignore" });
		runOrThrow("pg_ctl", [
			"-D",
			CLUSTER_DIR,
			"-l",
			PG_LOG,
			"-w",
			"-o",
			`-p ${port} -c listen_addresses=127.0.0.1 -c unix_socket_directories= -c fsync=off -c synchronous_commit=off -c max_connections=200`,
			"start",
		]);
		adminUrl = `postgres://postgres@127.0.0.1:${port}/postgres`;
		process.once("exit", () => {
			spawnSync("pg_ctl", ["-D", CLUSTER_DIR, "-m", "fast", "stop"], { stdio: "ignore" });
		});
	}

	const { Client } = fixtureRequire("pg");

	async function admin(run) {
		const client = new Client({ connectionString: adminUrl });
		await client.connect();
		try {
			return await run(client);
		} finally {
			await client.end();
		}
	}

	return {
		urlFor: (name) => withDatabase(adminUrl, name),
		exists: (name) =>
			admin(async (client) => {
				const { rowCount } = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [
					name,
				]);
				return rowCount > 0;
			}),
		// Names are generated by the harness from hex hashes and timestamps.
		create: (name, template) =>
			admin((client) =>
				client.query(`CREATE DATABASE "${name}"${template ? ` TEMPLATE "${template}"` : ""}`),
			),
		drop: (name) =>
			admin((client) => client.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`)),
	};
}

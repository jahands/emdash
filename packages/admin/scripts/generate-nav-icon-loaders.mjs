import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const index = readFileSync(
	new URL(
		"./dist/index.es.js",
		pathToFileURL(require.resolve("@phosphor-icons/react/package.json")),
	),
	"utf8",
);
const imports = new Map();
for (const match of index.matchAll(/import \{([^}]+)\} from "\.\/csr\/([^"]+)\.es\.js"/g)) {
	for (const binding of match[1].split(",")) {
		const [name, local] = binding.trim().split(/\s+as\s+/);
		imports.set(local, { name, file: match[2] });
	}
}
const entries = [];
for (const match of index.slice(index.lastIndexOf("export {")).matchAll(/\b(\w+) as (\w+)[,\n]/g)) {
	const binding = imports.get(match[1]);
	if (binding)
		entries.push(
			`${JSON.stringify(match[2])}: () => import("@phosphor-icons/react/dist/csr/${binding.file}").then(m => m.${binding.name}),`,
		);
}
if (entries.length < 1000) throw new Error("Could not read Phosphor icon exports");
writeFileSync(
	new URL("../src/lib/nav-icon-loaders.ts", import.meta.url),
	`// Generated by scripts/generate-nav-icon-loaders.mjs.\nimport type { Icon } from "@phosphor-icons/react";\n\nconst loaders: Record<string, () => Promise<Icon>> = {\n${entries.join("\n")}\n};\n\nexport async function loadNavIcon(name: string): Promise<Icon | undefined> {\nreturn Object.hasOwn(loaders, name) ? loaders[name]!() : undefined;\n}\n`,
);

/**
 * Writes src/components/phosphor-icon-names.ts, the names of every icon in the
 * installed @phosphor-icons/react. Run it after upgrading that package.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const iconsDir = join(
	dirname(require.resolve("@phosphor-icons/react/package.json")),
	"dist",
	"ssr",
);
const names = readdirSync(iconsDir)
	.filter((file) => file.endsWith(".es.js") && file !== "index.es.js")
	.map((file) => file.slice(0, -".es.js".length))
	.toSorted();

const target = join(
	dirname(fileURLToPath(import.meta.url)),
	"..",
	"src",
	"components",
	"phosphor-icon-names.ts",
);
writeFileSync(
	target,
	`// Generated by scripts/generate-phosphor-icon-names.js. Do not edit.\nexport const PHOSPHOR_ICON_NAMES: ReadonlySet<string> = new Set(\n\t"${names.join(" ")}".split(" "),\n);\n`,
);
console.log(`Wrote ${names.length} icon names to ${target}`);
